import * as React from 'react'
import * as DropdownMenuPrimitive from '@radix-ui/react-dropdown-menu'

import { cn } from '@renderer/lib/utils'
import { FLOATING_PANEL_SURFACE } from '@renderer/lib/floatingPanelSurface'

function ChevronRightIcon({ className }: { className?: string }): React.JSX.Element {
  return (
    <svg className={className} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2}>
      <path strokeLinecap="round" strokeLinejoin="round" d="m9 18 6-6-6-6" />
    </svg>
  )
}

function CheckIcon({ className }: { className?: string }): React.JSX.Element {
  return (
    <svg className={className} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2.5}>
      <path strokeLinecap="round" strokeLinejoin="round" d="M20 6 9 17l-5-5" />
    </svg>
  )
}

const DropdownMenu = ({
  onOpenChange,
  modal = false,
  ...props
}: React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.Root>): React.JSX.Element => {
  return (
    <DropdownMenuPrimitive.Root
      modal={modal}
      onOpenChange={(open) => {
        if (!open) {
          const activeElement = document.activeElement
          if (activeElement instanceof HTMLElement && activeElement.getAttribute('aria-haspopup') === 'menu') {
            activeElement.blur()
          }
        }
        onOpenChange?.(open)
      }}
      {...props}
    />
  )
}

